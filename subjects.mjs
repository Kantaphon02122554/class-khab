// คืนชื่อวิชา หรือ null ถ้าไม่ใช่รหัสวิชา (เช่น แนะแนว, กิจกรรม, ชุมนุม, พักกลางวัน) ให้ใช้ข้อความเดิม
export function subjectName(code, data = SUBJECT_DATA) {
  if (!ENABLE_NAMES || !code) return null;
  const c = String(code).trim();
  if (data.exact[c]) return data.exact[c];
  const m = c.match(/^([^\d\s]+)(\d)(\d)(\d)(\d{2})$/);
  if (!m) return null;
  const [, letter, , , type, seq] = m;
  const group = data.groups[letter];
  if (!group) return null;
  // ว...191-199: วิชาวิทยาการคำนวณ (ตามรูปแบบรหัสในหลักสูตร เช่น ว21192, ว22193) — ข้อสันนิษฐาน ควรให้โรงเรียนยืนยัน
  if (letter === 'ว' && Number(seq) >= 91) {
    return type === '2' ? 'วิทยาการคำนวณเพิ่มเติม' : 'วิทยาการคำนวณ';
  }
  return type === '2' ? `${group}เพิ่มเติม` : group;
}

// ข้อความแสดงผล: "ชื่อวิชา (รหัส)" หรือข้อความเดิมถ้าไม่ใช่รหัส
export function subjectLabel(code, data = SUBJECT_DATA) {
  const name = subjectName(code, data);
  return name ? `${name} (${code})` : code;
}

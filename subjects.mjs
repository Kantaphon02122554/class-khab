// วิชาเพิ่มเติมที่ชื่อเฉพาะโรงเรียน (เช่น ว30287) ให้เติมใน "exact" เมื่อได้รายชื่อจากโรงเรียน

// สวิตช์เปิด/ปิดการแสดงชื่อวิชา: false = แสดงเฉพาะรหัสวิชาเหมือนเดิม (รอรายชื่อวิชาที่ยืนยันแล้วจากโรงเรียน)
// เปลี่ยนเป็น true แล้วรัน scripts/import-schedule.mjs ใหม่ และอัปโหลด subjects.mjs ขึ้น GitHub
